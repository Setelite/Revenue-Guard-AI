const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');

const html=fs.readFileSync('index.html','utf8');
const app=new JSDOM(html,{
 url:'http://127.0.0.1:8000/',runScripts:'dangerously',pretendToBeVisual:true,
 beforeParse(window){window.scrollTo=()=>{};window.confirm=()=>true}
});
const d=app.window.document,storage=app.window.localStorage;
const click=selector=>{const el=d.querySelector(selector);assert.ok(el,'Missing '+selector);el.click()};
const tick=()=>new Promise(resolve=>setTimeout(resolve,12));
const set=(selector,value)=>{const el=d.querySelector(selector);assert.ok(el,'Missing '+selector);el.value=value;el.dispatchEvent(new app.window.Event('input',{bubbles:true}))};

(async()=>{
 assert.match(d.querySelector('h1').textContent,/Что будем/);
 assert.equal(d.querySelectorAll('.quick-action').length,4);
 assert.equal(d.querySelectorAll('.inspo-card').length,3);
 assert.equal(d.querySelectorAll('#bottomnav [data-route]').length,5);
 click('#settingsOpen');
 assert.equal(d.querySelectorAll('#bizIndustry option').length,7);
 set('#bizIndustry','food');
 set('#bizName','Кофейня Тест');
 set('#bizService','Завтраки');
 set('#bizAudience','Жители района');
 set('#bizAdvantage','В меню есть завтраки');
 set('#bizChannels','Instagram и Telegram');
 set('#bizPrice','350');
 d.querySelector('#bizForm').dispatchEvent(new app.window.Event('submit',{bubbles:true,cancelable:true}));
 click('#bottomnav [data-route="home"]');
 assert.match(d.querySelector('.industry-pill').textContent,/Кафе и еда/);
 click('.quick-action');
 assert.ok(d.querySelector('#taskText'));
 assert.match(d.querySelector('#taskText').value,/увеличить продажи/);
 set('#taskText','Хочу увеличить продажи завтраков в кофейне без скидок.');
 click('#createButton');
 await tick();
 assert.equal(d.querySelectorAll('[data-select]').length,3);
 const titles=[...d.querySelectorAll('.offer h3')].map(x=>x.textContent);
 assert.equal(new Set(titles).size,3,'Distinct local offer mechanics');
 assert.match(d.querySelector('#view').textContent,/Завтрак/i,'Sector product incorporated');
 assert.doesNotMatch(d.querySelector('#view').textContent,/мастеру|услугу салона/i);
 click('[data-select="1"]');
 click('#selectOffer');
 assert.ok(d.querySelector('#storyPreview'));
 assert.equal(d.querySelectorAll('[data-theme]').length,3);
 assert.equal(d.querySelectorAll('[data-asset]').length,3,'Content formats');
 click('[data-asset="reels"]');
 assert.match(d.querySelector('#assetText').value,/Кадр 1/);
 set('#assetText','Тестовый сценарий короткого видео');
 let current=JSON.parse(storage.getItem('rg-clean-v2')).campaigns[0];
 assert.equal(current.assets.reels,'Тестовый сценарий короткого видео');
 click('[data-asset="reply"]');
 assert.match(d.querySelector('#assetText').value,/Здравствуйте/);
 click('[data-theme="ink"]');
 assert.ok(d.querySelector('#storyPreview').classList.contains('theme-ink'));
 set('#offerTitle','Новый заголовок');
 assert.equal(d.querySelector('#storyTitle').textContent,'Новый заголовок');
 click('#approveOffer');
 assert.ok(d.querySelector('#markPublished'));
 click('#markPublished');
 assert.ok(d.querySelector('#addLead'));
 click('#addLead');
 assert.equal(JSON.parse(storage.getItem('rg-clean-v2')).leads[0].tracked,true);
 assert.match(d.querySelector('#view').textContent,/Обращений, отмеченных вручную/);
 assert.equal(JSON.parse(storage.getItem('rg-clean-v2')).leads.length,1);
 set('#paidAmount','4500');
 click('#addPayment');
 assert.match(d.querySelector('#view').textContent,/4\s?500/);
 assert.match(d.querySelector('#view').textContent,/Обращений/);
 click('#bottomnav [data-route="home"]');
 assert.equal(d.querySelectorAll('.inspo-card').length,3);
 click('#settingsOpen');
 set('#bizIndustry','retail');set('#bizName','Магазин света');set('#bizService','Светильники');set('#bizAdvantage','');
 d.querySelector('#bizForm').dispatchEvent(new app.window.Event('submit',{bubbles:true,cancelable:true}));
 click('#bottomnav [data-route="home"]');
 assert.match(d.querySelector('.industry-pill').textContent,/Магазин и товары/);
 click('#createIdea');
 set('#taskText','Хочу продать больше светильников без скидок');
 click('#createButton');
 await tick();
 assert.match(d.querySelector('#view').textContent,/Светильники/i);
 assert.equal(JSON.parse(storage.getItem('rg-clean-v2')).campaigns.length,2,'Prior campaigns preserved');
 console.log('PASS: food/retail profiles, 3 strategies, content pack, story themes, leads and payments');
 app.window.close();
})().catch(e=>{console.error(e);process.exitCode=1});
